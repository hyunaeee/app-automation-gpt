import fs from 'node:fs/promises';
import path from 'node:path';
import assert from 'node:assert/strict';
import { fileURLToPath } from 'node:url';
const root=fileURLToPath(new URL('../samples/atelier-mobile/',import.meta.url));
const read=async file=>JSON.parse(await fs.readFile(path.join(root,file),'utf8'));
const [report,apk,delivery]=await Promise.all([read('run-report.json'),read('apk-build-report.json'),read('delivery-report.json')]);
assert.equal(apk.runtimeVerification.status,'verified');
assert.equal(apk.sha256,report.apk.sha256);
assert.deepEqual(apk.sourceFileSha256,report.sourceFileSha256);
assert.ok(apk.runtimeVerification.checks.every(check=>check.passed));
assert.ok(delivery.checks.every(check=>check.passed));
report.emulator=apk.runtimeVerification;
report.delivery=delivery;
report.gallery=await read('gallery-report.json');
report.verifiedAt=new Date().toISOString();
await fs.writeFile(path.join(root,'run-report.json'),JSON.stringify(report,null,2));
const escape=value=>String(value).replace(/[&<>\"]/g,char=>({'&':'&amp;','<':'&lt;','>':'&gt;','\"':'&quot;'}[char]));
const native='<section id="android-verification"><h2>Android에서 직접 확인한 동작</h2><p>API 36 에뮬레이터에 같은 APK를 설치했습니다. 홈 → 디자인 → 견적 → 저장 → 앱 재실행 후 보관함까지 확인했습니다.</p><div class="checks">'+apk.runtimeVerification.checks.map(check=>'<div>✓ '+escape(check.name)+'</div>').join('')+'</div><div style="display:grid;grid-template-columns:repeat(3,minmax(0,1fr));gap:16px;align-items:start">'+['android-home','android-estimate','android-library-after-restart'].map(name=>`<a href="screenshots/${name}.png"><img src="screenshots/${name}.png" alt="${name}"></a>`).join('')+'</div><p class="subtle">검증한 APK SHA256: <code>'+apk.sha256+'</code></p></section>';
let html=await fs.readFile(path.join(root,'report.html'),'utf8');
html=html.replace(/<section id="android-verification">[\s\S]*?<\/section>/,'');
html=html.replace('<h2>샘플의 범위</h2>',native+'<h2>샘플의 범위</h2>');
if(!html.includes('id="product-asset"'))html=html.replace('<h2>02 · 이미지에서 실제 기능으로</h2>','<p id="product-asset" class="subtle">레퍼런스와 같은 제품 사진도 내장 image_gen으로 생성했습니다. <a href="design/tote-photo-v1.png">제품 이미지 원본</a> · <a href="design/tote-image-prompt.json">제품 이미지 프롬프트</a></p><h2>02 · 이미지에서 실제 기능으로</h2>');
await fs.writeFile(path.join(root,'report.html'),html);
console.log(JSON.stringify({androidChecks:apk.runtimeVerification.checks.length,deliveryChecks:delivery.checks.length,report:'samples/atelier-mobile/report.html'}));
